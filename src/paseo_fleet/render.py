"""Render per-platform provisioning artifacts. Pure functions; nothing here touches a machine."""

from __future__ import annotations

import base64
import re
import shlex
from urllib.parse import quote

from .inventory import Host, Inventory

SERVICE_NAME = "paseo-fleet"
LAUNCHD_LABEL = "dev.paseo-fleet.daemon"
TASK_NAME = "PaseoFleetDaemon"
DEFAULT_WORKSPACE = "~/paseo-workspaces"
DEFAULT_WORKSPACE_WINDOWS = "%USERPROFILE%\\paseo-workspaces"


def workspace_root(host: Host) -> str:
    if host.is_docker:
        return "/workspace"
    if host.workspace_root:
        return host.workspace_root
    return DEFAULT_WORKSPACE_WINDOWS if host.is_windows else DEFAULT_WORKSPACE


def _sh_path(path: str) -> str:
    """Quote a path for sh, expanding a leading ~/ to $HOME."""
    if path == "~":
        return '"$HOME"'
    if path.startswith("~/"):
        return '"$HOME"/' + shlex.quote(path[2:])
    return shlex.quote(path)


def _fill(template: str, values: dict[str, str]) -> str:
    out = template
    for key, value in values.items():
        out = out.replace(f"@@{key}@@", value)
    leftover = re.findall(r"@@[A-Z_]+@@", out)
    if leftover:
        raise ValueError(f"unfilled template placeholders: {leftover}")
    return out


def connection(host: Host, password: str | None = None) -> str:
    """Endpoint string accepted by `paseo --host`."""
    if host.transport == "ssh":
        target = host.ssh if not host.ssh_port else f"{host.ssh}:{host.ssh_port}"
        return f"ssh://{target}?daemonPort={host.daemon_port}"
    if password:
        return f"tcp://127.0.0.1:{host.daemon_port}?password={quote(password, safe='')}"
    return f"127.0.0.1:{host.daemon_port}"


def redact(text: str, secrets: list[str]) -> str:
    for secret in secrets:
        if secret:
            text = text.replace(secret, "***")
    return text


POSIX_TEMPLATE = r"""#!/bin/sh
# Generated by paseo-fleet for host @@HOST_ID@@. Idempotent; safe to re-run.
set -eu
OS=@@OS@@
NODE_VER=@@NODE_VER@@
PASEO_VER=@@PASEO_VER@@
PORT=@@PORT@@
BASE="$HOME/.local/share/paseo-fleet"
WORKSPACE=@@WORKSPACE@@
fail() { echo "paseo-fleet: $*" >&2; exit 1; }

case "$(uname -m)" in
  x86_64|amd64) ARCH=x64 ;;
  aarch64|arm64) ARCH=arm64 ;;
  armv7l) ARCH=armv7l ;;
  *) fail "unsupported architecture $(uname -m)" ;;
esac
if [ "$OS" = linux ]; then EXT=tar.xz; else EXT=tar.gz; fi
for tool in curl tar; do command -v "$tool" >/dev/null || fail "$tool is required"; done

NODE_DIR="$BASE/node-v$NODE_VER"
mkdir -p "$BASE" "$HOME/.local/bin" "$HOME/.config/paseo-fleet"
if [ ! -x "$NODE_DIR/bin/node" ]; then
  tmp="$(mktemp -d)"
  trap 'rm -rf "$tmp"' EXIT
  file="node-v$NODE_VER-$OS-$ARCH.$EXT"
  curl -fsSL -o "$tmp/$file" "https://nodejs.org/dist/v$NODE_VER/$file"
  curl -fsSL -o "$tmp/SHASUMS256.txt" "https://nodejs.org/dist/v$NODE_VER/SHASUMS256.txt"
  expected="$(grep " $file\$" "$tmp/SHASUMS256.txt" | cut -d' ' -f1)"
  [ -n "$expected" ] || fail "no published checksum for $file"
  if command -v sha256sum >/dev/null; then actual="$(sha256sum "$tmp/$file" | cut -d' ' -f1)"
  else actual="$(shasum -a 256 "$tmp/$file" | cut -d' ' -f1)"; fi
  [ "$expected" = "$actual" ] || fail "checksum mismatch for $file"
  mkdir "$tmp/x"
  tar -xf "$tmp/$file" -C "$tmp/x"
  rm -rf "$NODE_DIR"
  mv "$tmp/x/node-v$NODE_VER-$OS-$ARCH" "$NODE_DIR"
fi
ln -sfn "$NODE_DIR" "$BASE/node"
export PATH="$BASE/node/bin:$PATH"

mkdir -p "$BASE/cli"
npm install --prefix "$BASE/cli" --no-audit --no-fund --loglevel=error @@PACKAGES@@
"$BASE/cli/node_modules/.bin/paseo" --version >/dev/null || fail "paseo CLI failed to run"

cat > "$HOME/.local/bin/paseo" <<WRAPPER
#!/bin/sh
export PATH="$BASE/node/bin:$BASE/cli/node_modules/.bin:\$PATH"
exec "$BASE/cli/node_modules/.bin/paseo" "\$@"
WRAPPER
chmod 755 "$HOME/.local/bin/paseo"

mkdir -p "$WORKSPACE"
ENV_FILE="$HOME/.config/paseo-fleet/daemon.env"
umask 077
@@ENV_WRITE@@
touch "$ENV_FILE"
chmod 600 "$ENV_FILE"
umask 022

cat > "$BASE/run-daemon.sh" <<RUNNER
#!/bin/sh
export PATH="$BASE/node/bin:$BASE/cli/node_modules/.bin:\$HOME/.local/bin:/usr/local/bin:/usr/bin:/bin:/opt/homebrew/bin"
export PASEO_LISTEN=127.0.0.1:$PORT
set -a
. "$ENV_FILE"
set +a
cd "$WORKSPACE"
exec "$BASE/cli/node_modules/.bin/paseo" daemon run
RUNNER
chmod 755 "$BASE/run-daemon.sh"

@@SERVICE@@

i=0
until curl -fsS "http://127.0.0.1:$PORT/api/health" >/dev/null 2>&1; do
  i=$((i + 1))
  [ "$i" -lt 45 ] || fail "daemon did not become healthy on 127.0.0.1:$PORT"
  sleep 1
done
echo "paseo-fleet: @@HOST_ID@@ healthy on 127.0.0.1:$PORT (paseo $PASEO_VER, node $NODE_VER)"
"""

SYSTEMD_BLOCK = r"""UNIT_DIR="$HOME/.config/systemd/user"
mkdir -p "$UNIT_DIR"
cat > "$UNIT_DIR/@@SERVICE_NAME@@.service" <<UNIT
[Unit]
Description=Paseo daemon (paseo-fleet)
After=network-online.target

[Service]
Type=simple
ExecStart=$BASE/run-daemon.sh
Restart=on-failure
RestartSec=5
@@LIMITS@@
[Install]
WantedBy=default.target
UNIT
export XDG_RUNTIME_DIR="${XDG_RUNTIME_DIR:-/run/user/$(id -u)}"
systemctl --user daemon-reload
systemctl --user enable @@SERVICE_NAME@@.service >/dev/null
systemctl --user restart @@SERVICE_NAME@@.service
if ! loginctl enable-linger "$(id -un)" 2>/dev/null; then
  echo "paseo-fleet: WARNING could not enable linger; daemon stops when the last login session ends." >&2
  echo "paseo-fleet: run once as an administrator: sudo loginctl enable-linger $(id -un)" >&2
fi"""

LAUNCHD_BLOCK = r"""PLIST="$HOME/Library/LaunchAgents/@@LABEL@@.plist"
mkdir -p "$HOME/Library/LaunchAgents" "$HOME/Library/Logs"
cat > "$PLIST" <<PLISTEOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>@@LABEL@@</string>
  <key>ProgramArguments</key><array><string>$BASE/run-daemon.sh</string></array>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
@@NICE@@  <key>StandardOutPath</key><string>$HOME/Library/Logs/paseo-fleet.log</string>
  <key>StandardErrorPath</key><string>$HOME/Library/Logs/paseo-fleet.log</string>
</dict></plist>
PLISTEOF
launchctl bootout "gui/$(id -u)/@@LABEL@@" 2>/dev/null || true
launchctl bootstrap "gui/$(id -u)" "$PLIST"
launchctl kickstart -k "gui/$(id -u)/@@LABEL@@"
"""


def _packages(inv: Inventory) -> str:
    return " ".join(shlex.quote(p) for p in (f"@getpaseo/cli@{inv.paseo_version}", *inv.agents))


def _env_write(env_content: str | None) -> str:
    if env_content is None:
        return '[ -f "$ENV_FILE" ] || : > "$ENV_FILE"'
    encoded = base64.b64encode(env_content.encode()).decode()
    return f"printf %s {encoded} | base64 -d > \"$ENV_FILE\""


def render_posix(host: Host, inv: Inventory, env_content: str | None = None) -> str:
    if host.platform == "linux":
        lines = []
        limits = host.limits
        if "nice" in limits:
            lines.append(f"Nice={limits['nice']}")
        if "memory" in limits:
            lines.append(f"MemoryMax={limits['memory']}")
        if "cpus" in limits:
            lines.append(f"CPUQuota={int(float(limits['cpus']) * 100)}%")
        limit_text = "\n".join(lines) + ("\n" if lines else "")
        service = _fill(SYSTEMD_BLOCK, {"SERVICE_NAME": SERVICE_NAME, "LIMITS": limit_text})
        os_name = "linux"
    elif host.platform == "macos":
        nice = host.limits.get("nice")
        nice_xml = f"  <key>Nice</key><integer>{nice}</integer>\n" if nice is not None else ""
        service = _fill(LAUNCHD_BLOCK, {"LABEL": LAUNCHD_LABEL, "NICE": nice_xml})
        os_name = "darwin"
    else:
        raise ValueError(f"{host.id}: not a POSIX platform")
    return _fill(POSIX_TEMPLATE, {
        "HOST_ID": host.id, "OS": os_name, "NODE_VER": inv.node_version,
        "PASEO_VER": inv.paseo_version, "PORT": str(host.daemon_port),
        "WORKSPACE": _sh_path(workspace_root(host)), "PACKAGES": _packages(inv),
        "ENV_WRITE": _env_write(env_content), "SERVICE": service,
    })


WINDOWS_TEMPLATE = r"""# Generated by paseo-fleet for host @@HOST_ID@@. Idempotent; safe to re-run.
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
$nodeVer = '@@NODE_VER@@'
$port = @@PORT@@
$base = Join-Path $env:LOCALAPPDATA 'paseo-fleet'
$workspace = [Environment]::ExpandEnvironmentVariables('@@WORKSPACE@@')
$arch = if ($env:PROCESSOR_ARCHITECTURE -eq 'ARM64') { 'arm64' } else { 'x64' }
New-Item -ItemType Directory -Force -Path $base, $workspace | Out-Null

$nodeDir = Join-Path $base "node-v$nodeVer"
if (-not (Test-Path (Join-Path $nodeDir 'node.exe'))) {
  $file = "node-v$nodeVer-win-$arch.zip"
  $tmp = Join-Path ([IO.Path]::GetTempPath()) ([guid]::NewGuid().ToString())
  New-Item -ItemType Directory -Path $tmp | Out-Null
  try {
    Invoke-WebRequest -UseBasicParsing "https://nodejs.org/dist/v$nodeVer/$file" -OutFile (Join-Path $tmp $file)
    $sums = (Invoke-WebRequest -UseBasicParsing "https://nodejs.org/dist/v$nodeVer/SHASUMS256.txt").Content
    $line = ($sums -split "`n") | Where-Object { $_ -match [regex]::Escape(" $file") } | Select-Object -First 1
    if (-not $line) { throw "no published checksum for $file" }
    $expected = ($line -split '\s+')[0].ToLower()
    $actual = (Get-FileHash (Join-Path $tmp $file) -Algorithm SHA256).Hash.ToLower()
    if ($expected -ne $actual) { throw "checksum mismatch for $file" }
    Expand-Archive (Join-Path $tmp $file) -DestinationPath $tmp
    if (Test-Path $nodeDir) { Remove-Item -Recurse -Force $nodeDir }
    Move-Item (Join-Path $tmp "node-v$nodeVer-win-$arch") $nodeDir
  } finally { Remove-Item -Recurse -Force $tmp -ErrorAction SilentlyContinue }
}

$cli = Join-Path $base 'cli'
New-Item -ItemType Directory -Force -Path $cli | Out-Null
$env:PATH = "$nodeDir;" + $env:PATH
& (Join-Path $nodeDir 'npm.cmd') install --prefix $cli --no-audit --no-fund --loglevel=error @@PACKAGES@@
if ($LASTEXITCODE -ne 0) { throw 'npm install failed' }
$paseo = Join-Path $cli 'node_modules\.bin\paseo.cmd'
& $paseo --version | Out-Null
if ($LASTEXITCODE -ne 0) { throw 'paseo CLI failed to run' }

$envFile = Join-Path $base 'daemon.env'
@@ENV_WRITE@@
$acl = Get-Acl $envFile
$acl.SetAccessRuleProtection($true, $false)
$acl.Access | ForEach-Object { $acl.RemoveAccessRule($_) | Out-Null }
$acl.AddAccessRule((New-Object Security.AccessControl.FileSystemAccessRule($env:USERNAME, 'FullControl', 'Allow')))
Set-Acl $envFile $acl

$runner = Join-Path $base 'run-daemon.ps1'
@"
`$ErrorActionPreference = 'Stop'
`$env:PATH = "$nodeDir;$cli\node_modules\.bin;" + `$env:PATH
`$env:PASEO_LISTEN = '127.0.0.1:$port'
Get-Content '$envFile' | ForEach-Object {
  if (`$_ -match '^\s*([A-Za-z_][A-Za-z0-9_]*)=(.*)$') { Set-Item -Path "env:`$(`$Matches[1])" -Value `$Matches[2] }
}
Set-Location '$workspace'
& '$paseo' daemon run
"@ | Set-Content -Path $runner -Encoding UTF8

$userId = [Security.Principal.WindowsIdentity]::GetCurrent().Name
$action = New-ScheduledTaskAction -Execute 'powershell.exe' -Argument "-NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File `"$runner`""
$trigger = New-ScheduledTaskTrigger -AtLogOn -User $userId
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -RestartCount 99 -RestartInterval (New-TimeSpan -Minutes 1) -ExecutionTimeLimit (New-TimeSpan -Seconds 0) -MultipleInstances IgnoreNew
$principal = New-ScheduledTaskPrincipal -UserId $userId -LogonType Interactive -RunLevel Limited
Stop-ScheduledTask -TaskName '@@TASK@@' -ErrorAction SilentlyContinue
Register-ScheduledTask -TaskName '@@TASK@@' -Action $action -Trigger $trigger -Settings $settings -Principal $principal -Force | Out-Null
Start-ScheduledTask -TaskName '@@TASK@@'

$ok = $false
for ($i = 0; $i -lt 45; $i++) {
  try { Invoke-WebRequest "http://127.0.0.1:$port/api/health" -UseBasicParsing | Out-Null; $ok = $true; break } catch { Start-Sleep -Seconds 1 }
}
if (-not $ok) { throw "daemon did not become healthy on 127.0.0.1:$port" }
Write-Host "paseo-fleet: @@HOST_ID@@ healthy on 127.0.0.1:$port (paseo @@PASEO_VER@@, node $nodeVer)"
"""


def render_windows(host: Host, inv: Inventory, env_content: str | None = None) -> str:
    if env_content is None:
        env_write = "if (-not (Test-Path $envFile)) { New-Item -ItemType File -Path $envFile | Out-Null }"
    else:
        encoded = base64.b64encode(env_content.encode()).decode()
        env_write = (f"[IO.File]::WriteAllBytes($envFile, [Convert]::FromBase64String('{encoded}'))")
    packages = " ".join(f"'{p}'" for p in (f"@getpaseo/cli@{inv.paseo_version}", *inv.agents))
    return _fill(WINDOWS_TEMPLATE, {
        "HOST_ID": host.id, "NODE_VER": inv.node_version, "PASEO_VER": inv.paseo_version,
        "PORT": str(host.daemon_port), "WORKSPACE": workspace_root(host).replace("'", "''"),
        "PACKAGES": packages, "ENV_WRITE": env_write, "TASK": TASK_NAME,
    })


def docker_project(host: Host) -> str:
    return f"paseo-fleet-{host.id}"


def render_docker_files(host: Host, inv: Inventory, has_agent_env: bool) -> dict[str, str]:
    packages = " ".join(shlex.quote(p) for p in inv.agents)
    dockerfile = f"FROM ghcr.io/getpaseo/paseo:{inv.paseo_version}\n"
    if packages:
        dockerfile += f"USER root\nRUN npm install -g --no-audit --no-fund --loglevel=error {packages}\n"
    env_files = "      - .env\n" + ("      - agent.env\n" if has_agent_env else "")
    limits = ""
    if "memory" in host.limits:
        limits += f"    mem_limit: {host.limits['memory'].lower()}\n"
    if "cpus" in host.limits:
        limits += f"    cpus: {host.limits['cpus']}\n"
    if host.workspace_mount:
        workspace_volume, workspace_decl = host.workspace_mount.replace(chr(92), "/"), ""
    else:
        workspace_volume, workspace_decl = "workspace", "  workspace:\n"
    compose = (
        "services:\n"
        "  paseo:\n"
        "    build: .\n"
        f"    image: paseo-fleet/{host.id}:{inv.paseo_version}\n"
        f"    container_name: {docker_project(host)}\n"
        "    restart: unless-stopped\n"
        "    ports:\n"
        f"      - \"127.0.0.1:{host.daemon_port}:6767\"\n"
        "    env_file:\n"
        f"{env_files}"
        f"{limits}"
        "    volumes:\n"
        "      - paseo-home:/home/paseo\n"
        f"      - \"{workspace_volume}:/workspace\"\n"
        "volumes:\n"
        "  paseo-home:\n"
        f"{workspace_decl}"
    )
    return {"Dockerfile": dockerfile, "compose.yaml": compose}


DOCKER_REMOTE_TEMPLATE = r"""#!/bin/sh
# Generated by paseo-fleet for docker host @@HOST_ID@@. Idempotent.
set -eu
command -v docker >/dev/null || { echo "paseo-fleet: docker is required" >&2; exit 1; }
DIR="$HOME/.local/share/paseo-fleet/docker/@@HOST_ID@@"
mkdir -p "$DIR"
umask 077
@@WRITES@@
cd "$DIR"
docker compose -p @@PROJECT@@ up -d --build
i=0
until curl -fsS "http://127.0.0.1:@@PORT@@/api/health" >/dev/null 2>&1; do
  i=$((i + 1))
  [ "$i" -lt 60 ] || { echo "paseo-fleet: container did not become healthy" >&2; exit 1; }
  sleep 1
done
echo "paseo-fleet: @@HOST_ID@@ healthy on 127.0.0.1:@@PORT@@"
"""


def render_docker_remote(host: Host, files: dict[str, str]) -> str:
    writes = []
    for name, content in files.items():
        encoded = base64.b64encode(content.encode()).decode()
        writes.append(f"printf %s {encoded} | base64 -d > \"$DIR/{name}\"")
    return _fill(DOCKER_REMOTE_TEMPLATE, {
        "HOST_ID": host.id, "WRITES": "\n".join(writes),
        "PROJECT": docker_project(host), "PORT": str(host.daemon_port),
    })
